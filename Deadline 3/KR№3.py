def создать_степень(степень):
    def возвести(число):
        результат = число ** степень
        return результат
    return возвести


class Математика:
    @classmethod
    def степени_чисел(cls, числа, степень):
        функция = создать_степень(степень)
        ответы = []
        for ч in числа:
            ответы.append(функция(ч))
        return ответы


if __name__ == "__main__":
    квадрат = создать_степень(2)
    куб = создать_степень(3)
    
    print("Проверка работы:")
    print(f"квадрат(4) = {квадрат(4)}")
    print(f"куб(3) = {куб(3)}")
    print(f"квадрат(5) = {квадрат(5)}")
    
    список_чисел = [1, 2, 3, 4, 5]
    
    print("\nЧерез класс Математика:")
    квадраты = Математика.степени_чисел(список_чисел, 2)
    кубы = Математика.степени_чисел(список_чисел, 3)
    
    print(f"Исходные: {список_чисел}")
    print(f"В квадрате: {квадраты}")
    print(f"В кубе: {кубы}")